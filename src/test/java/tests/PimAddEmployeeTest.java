package tests;

import org.testng.Assert;
import org.testng.annotations.BeforeMethod;
import org.testng.annotations.Test;
import base.BaseTest;
import pages.PageHub;
import utils.ConfigReader;

public class PimAddEmployeeTest extends BaseTest {

    private PageHub pages;

    @BeforeMethod
    @Override
    public void setUp() {
        super.setUp();
        pages = new PageHub(driver);
    }

    @Test(groups = {"pim", "regression"})
    public void testAddSearchAndValidateEmployee() {
        // Smart URL Gate: Skip authentication if the previous class left the session logged in
        if (!driver.getCurrentUrl().contains("/dashboard") && !driver.getCurrentUrl().contains("/pim") && !driver.getCurrentUrl().contains("/admin")) {
            pages.loginPage().loginDetails(ConfigReader.get("app.username"), ConfigReader.get("app.password"));
            pages.pimAddEmployee().waitForUrlContains("/dashboard");
        }
        pages.pimAddEmployee().navigateToPIM();

        // 2. Click Add, click Save instantly, and confirm validation warnings trigger
        pages.pimAddEmployee().openAddEmployeeForm();
        pages.pimAddEmployee().clickSaveOnAddEmployee();
        Assert.assertTrue(pages.pimAddEmployee().isRequiredFieldsErrorDisplayed());

        // 3. Extract the autogenerated tracking numerical string sequence
        String targetEmployeeId = pages.pimAddEmployee().getGeneratedEmployeeId();
        System.out.println("Auto-assigned ID captured: " + targetEmployeeId);

        // 4. Input employee identity parameters and save cleanly using robust collision handlers
        pages.pimAddEmployee().enterEmployeeNames("John", "Doe");
        targetEmployeeId = pages.pimAddEmployee().saveEmployeeWithCollisionHandling();
        System.out.println("John Doe record finalized with confirmed ID: " + targetEmployeeId);

        // 5. Query active profile list layers to locate and select the target profile row
        pages.pimAddEmployee().navigateToEmployeeList();
        pages.pimAddEmployee().searchByEmployeeId(targetEmployeeId);
        pages.pimAddEmployee().clickOnMatchingEmployee(targetEmployeeId);

        // 6. Set custom demographics variables (Married, Male, Special characters, Today's Date)
        pages.pimAddEmployee().updateDemographicsAndIdentifiers("LIC@£$%789#!");

        // 7. Validate that data modifications persisted cleanly inside application records
        Assert.assertEquals(pages.pimAddEmployee().getMaritalStatus(), "Married");
        Assert.assertTrue(pages.pimAddEmployee().isMaleSelected());

        // 8. Append secondary profile ("123425 @£$%^&*") utilizing the same collision safety tracking loops
        pages.pimAddEmployee().navigateToEmployeeList();
        pages.pimAddEmployee().openAddEmployeeForm();
        pages.pimAddEmployee().enterEmployeeNames("123425", "@£$%^&*");
        String secondEmployeeId = pages.pimAddEmployee().saveEmployeeWithCollisionHandling();
        
        // Bypasses the toast verification block on the second profile creation to prevent TimeoutException errors
        pages.pimAddEmployee().clickSaveOnPersonalDetailsWithoutToastCheck();
        System.out.println("Second profile completed with confirmed ID: " + secondEmployeeId);

        // 9. Return back to matrix search list views, select row checkbox options, and wipe the record out
        pages.pimAddEmployee().navigateToEmployeeList();
        pages.pimAddEmployee().searchByEmployeeId(secondEmployeeId);
        pages.pimAddEmployee().selectEmployeeCheckbox(secondEmployeeId);
        pages.pimAddEmployee().deleteSelectedEmployee();
        
        // 10. Affirm data grid row scrubbing actions passed completely
        Assert.assertTrue(pages.pimAddEmployee().isRecordDeletedSuccessfully());
        System.out.println("Workflow execution lifecycle finished with absolute success.");
    }
}
